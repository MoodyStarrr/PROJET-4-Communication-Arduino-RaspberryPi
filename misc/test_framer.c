#include <framer.h>
#include <stdlib.h>
#include <stdio.h>
#include <stdbool.h>

typedef struct {
  framer_context_t ctx;
  uint8_t message[SIZE_MAX_MSG];
  size_t length;
  bool success;
}Framer_Values;

int main(void){
  int error = 0;
  framer_context_t init;
  framer_reset(&init);

  Framer_Values array[] = {
  {init,{0x7E,0x01,0x05,0xA6,0x12,0x02,0x10,0x14,0x00,0x00,0x00,0x0C,0xFF},13,1}, // Good
  {init,{0x7E,0x01,0x05,0xA6,0x12,0x02,0x10,0x14,0x00,0x00,0x00,0x0D,0xFF},13,0}, // Wrong CRC
  {init,{0x7E,0x01,0x06,0xA6,0x12,0x02,0x10,0x14,0x7D,0x7E,0x00,0x6C,0xFF},13,1}, // Byte Stuffing
  {init,{0x7E,0x01,0x06,0xA6,0x12,0x02,0x10,0x14,0x7D,0x7D,0x00,0x6C,0xFF},13,1}, // Byte Stuffing 2
  {init,{0x03,0x7E,0x01,0x06,0xA6,0x12,0x02,0x10,0x14,0x7D,0x7E,0x00,0x6C,0xFF},14,1}, // Byte before Start
  {init,{0x7E,0x01,0x00,0xA6,0x12,0x02,0x10,0x14,0x7D,0x7E,0x00,0x6C,0xFF},13,0}, // length = 0
  {init,{0x7E,0x01,0x08,0xA6,0x12,0x02,0x10,0x14,0x15,0x16,0x17,0x2B,0xFF},13,1}, // length = 8
  {init,{0x7E,0x01,0x09,0xA6,0x12,0x02,0x10,0x14,0x15,0x16,0x17,0x18,0x2B,0xFF},14,0}, // length = 9
  {init,{0x03,0x7E,0x01,0x05,0xA6,0x12,0x02,0x10,0x14,0x00,0x00,0x00,0x0C},13,0}, // No End Frame
  };

  for(size_t i = 0 ; i < (sizeof(array)/sizeof(Framer_Values)) ; i++){
    for(size_t j = 0 ; j < array[i].length ; j++){

      framer_return_t state = frame_parser(array[i].message[j],&(array[i].ctx));
      switch (state)
      {
        case FRAME_IN_PROGRESS:
          printf("Currently in %zu octet of %zu message.\n",j,i);
        break;
        case FRAME_VALID:
          if(!array[i].success){
            printf("%zu is valid. Incorrect.\n",i);
            error++;
          }else{
            printf("%zu is valid. Correct.\n",i);
          }
        break;
        case FRAME_INVALID:
          if(array[i].success){
            printf("%zu is invalid. Incorrect.\n",i);
            error++;
          }else{
            printf("%zu is invalid. Correct.\n",i);
          }
        break;
      }
    }
  }

  if(error)
    exit(EXIT_FAILURE);
  exit(EXIT_SUCCESS);
}
